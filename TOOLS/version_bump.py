#!/usr/bin/env python3
"""Release version bump: SPECS/VERSIONING_POLICY_v1.md section 5 as one command.

    python TOOLS/version_bump.py 1.1.0

``VERSION`` is the single source of truth; this tool moves it and every lockstep copy
together, then re-freezes the manifest and pins the bundle digest, so a bump cannot
miss a copy, keep checking the old manifest, or leave the bundle without a pin (each
of which happened or was possible with the manual procedure).

Preconditions (checked before anything is written; any failure writes nothing):

* ``NEW`` is strict SemVer 2.0.0 (``ark_semver``) and has higher precedence than the
  current ``VERSION`` (semver.org section 11), so a typo cannot move a release backwards;
* the tree has no version drift (every lockstep copy names the current ``VERSION``);
* ``CHANGELOG.md`` already has a ``## [NEW]`` section: section 3.1 requires release
  notes that classify the change and name every verdict loosening, and those are
  written by a person before the bump, not generated by it;
* ``artifacts/FREEZE_MANIFEST_vNEW.json`` and its bundle pin do not exist yet.

Then, in this order: rewrite the lockstep copies, write the new manifest (the previous
one with ``artifact`` renamed; the previous manifest stays as a historical record), run
``TOOLS/freeze_manifest.py --regenerate`` and ``TOOLS/release_bundle.py --pin`` as fresh
processes (``freeze_manifest`` derives its own path at import time), remove the previous
bundle pin (a pin only exists for the version a tree can build), and check
:func:`version_drift` once more.

A failure after the first write (a tool exit, a timeout, drift after the bump, an
interrupt) puts every touched path back to its bytes from before the bump, reads each
back, and names any it could not restore as ``ROLLBACK INCOMPLETE``. That is in-process
best effort, not a crash-atomic transaction and not a lock: run the bump in a clean
checkout, where ``git status`` shows anything a killed process left behind.

The lockstep rules live here, in :func:`version_drift`; ``tests/test_version_consistency.py``
imports them, so the tool and the PR gate cannot disagree.

Stdlib only. Exit codes: 0 bumped, 1 refused or failed, 2 usage error.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import ark_json  # noqa: E402  (the one JSON grammar)
from ark_semver import SEMVER_RE  # noqa: E402  (the one SemVer grammar)

TOOLS = Path(__file__).resolve().parent
PROV_EXAMPLE = "examples/minimal_run/provenance/prov.json"
_DEFAULT_MANIFEST_RE = re.compile(
    r'^DEFAULT_MANIFEST = os\.path\.join\("artifacts", "FREEZE_MANIFEST_v([^"]+)\.json"\)$', re.M
)


class BumpError(ValueError):
    """The bump must not proceed."""


# ------------------------------- SemVer precedence ------------------------------- #
def _precedence_key(version: str) -> Tuple:
    """Sort key implementing semver.org section 11 (build metadata ignored)."""
    match = SEMVER_RE.fullmatch(version)
    if not match:
        raise BumpError(f"not a strict SemVer 2.0.0 version: {version!a}")
    core, _, rest = version.partition("+")[0].partition("-")
    major, minor, patch = (int(x) for x in core.split("."))
    if not rest:
        return (major, minor, patch, 1, ())  # a release outranks all its pre-releases
    ids = []
    for ident in rest.split("."):
        # Numeric identifiers sort numerically and below alphanumeric ones.
        ids.append((0, int(ident), "") if ident.isdigit() else (1, 0, ident))
    return (major, minor, patch, 0, tuple(ids))


def is_newer(new: str, old: str) -> bool:
    return _precedence_key(new) > _precedence_key(old)


# --------------------------------- lockstep rules -------------------------------- #
def read_version(root: Path) -> str:
    from release_gate import ReleaseGateError, read_version as _read

    try:
        return _read(root)
    except ReleaseGateError as exc:
        raise BumpError(str(exc)) from exc


def _text(root: Path, rel: str) -> str:
    return (root / rel).read_text(encoding="utf-8")


def version_drift(root: Path, version: Optional[str] = None) -> List[str]:
    """Every lockstep copy that disagrees with ``version`` (default: ``VERSION``). Empty = consistent."""
    v = version or read_version(root)
    drift: List[str] = []

    for spec in sorted((root / "SPECS").glob("*.md")):
        m = re.search(r"^Version: (\S+)$", spec.read_text(encoding="utf-8"), re.M)
        if not m or m.group(1) != v:
            drift.append(f"SPECS/{spec.name}: Version header {m.group(1) if m else None!r}")

    fm = _DEFAULT_MANIFEST_RE.search(_text(root, "TOOLS/freeze_manifest.py"))
    if not fm or fm.group(1) != v:
        drift.append(f"TOOLS/freeze_manifest.py: DEFAULT_MANIFEST names {fm.group(1) if fm else None!r}")
    manifest = root / "artifacts" / f"FREEZE_MANIFEST_v{v}.json"
    if not manifest.is_file():
        drift.append(f"artifacts/{manifest.name}: missing")
    else:
        try:
            artifact = ark_json.load_path(str(manifest)).get("artifact")
        except (ValueError, AttributeError):
            artifact = None
        if artifact != f"ARK-Core_v{v}_freeze":
            drift.append(f"artifacts/{manifest.name}: artifact field {artifact!a}")
    if not (root / "artifacts" / f"RELEASE_BUNDLE_v{v}.sha256").is_file():
        drift.append(f"artifacts/RELEASE_BUNDLE_v{v}.sha256: missing (python TOOLS/release_bundle.py --pin)")

    cff = re.search(r'^version: "?([^"\s]+)"?$', _text(root, "CITATION.cff"), re.M)
    if not cff or cff.group(1) != v:
        drift.append("CITATION.cff: version")
    if not re.search(rf"^- \*\*Version:\*\* {re.escape(v)} ", _text(root, "AGENTS.md"), re.M):
        drift.append("AGENTS.md: Version line")
    if not re.search(rf"^\*\*Status:\*\* v{re.escape(v)} ", _text(root, "README.md"), re.M):
        drift.append("README.md: Status line")
    if not re.search(rf"^## \[{re.escape(v)}\]", _text(root, "CHANGELOG.md"), re.M):
        drift.append(f"CHANGELOG.md: no '## [{v}]' section")

    prov = ark_json.load_path(str(root / PROV_EXAMPLE))
    claimed = [a.get("tool_version") for a in prov.get("activities", []) if "tool_version" in a]
    claimed += [a.get("version") for a in prov.get("agents", []) if a.get("kind") == "tool"]
    if not claimed or any(c != v for c in claimed):
        drift.append(f"{PROV_EXAMPLE}: tool versions {claimed}")
    return drift


# ------------------------------------ rewrite ------------------------------------ #
def _replace_line(text: str, pattern: str, old: str, new: str, where: str) -> str:
    """Replace ``old`` by ``new`` inside the single line matching ``pattern``."""
    lines = text.splitlines(keepends=True)
    hits = [i for i, line in enumerate(lines) if re.match(pattern, line)]
    if len(hits) != 1:
        raise BumpError(f"{where}: expected exactly one line matching {pattern!a}, found {len(hits)}")
    lines[hits[0]] = lines[hits[0]].replace(old, new)
    return "".join(lines)


def planned_edits(root: Path, old: str, new: str) -> Dict[str, str]:
    """``relative path -> new text`` for every lockstep copy. Pure: writes nothing."""
    edits: Dict[str, str] = {"VERSION": new + "\n"}
    for spec in sorted((root / "SPECS").glob("*.md")):
        rel = f"SPECS/{spec.name}"
        edits[rel] = _replace_line(_text(root, rel), rf"Version: {re.escape(old)}$", old, new, rel)
    rel = "TOOLS/freeze_manifest.py"
    edits[rel] = _replace_line(
        _text(root, rel), r"DEFAULT_MANIFEST = ", f"FREEZE_MANIFEST_v{old}.json", f"FREEZE_MANIFEST_v{new}.json", rel
    )
    edits["CITATION.cff"] = _replace_line(_text(root, "CITATION.cff"), r"version: ", old, new, "CITATION.cff")
    edits["AGENTS.md"] = _replace_line(_text(root, "AGENTS.md"), r"- \*\*Version:\*\* ", old, new, "AGENTS.md")
    edits["README.md"] = _replace_line(_text(root, "README.md"), r"\*\*Status:\*\* v", old, new, "README.md")
    prov = _text(root, PROV_EXAMPLE)
    prov_new = re.sub(
        rf'("(?:tool_version|version)": ")({re.escape(old)})(")', lambda m: m.group(1) + new + m.group(3), prov
    )
    # The textual edit keeps the file's layout; the structural check proves it changed
    # exactly the fields version_drift reads (activities[*].tool_version and the version
    # of agents of kind "tool") and nothing else, e.g. not the "version" of another agent
    # or entity, and that it did not miss a field written in another JSON layout.
    expected = ark_json.loads(prov)
    for act in expected.get("activities", []):
        if "tool_version" in act:
            act["tool_version"] = new
    for agent in expected.get("agents", []):
        if agent.get("kind") == "tool":
            agent["version"] = new
    if ark_json.loads(prov_new) != expected:
        raise BumpError(
            f"{PROV_EXAMPLE}: the textual version rewrite does not equal the structural one "
            "(a non-tool 'version' equal to the old version, or a field in another layout); edit it by hand"
        )
    edits[PROV_EXAMPLE] = prov_new

    old_manifest = root / "artifacts" / f"FREEZE_MANIFEST_v{old}.json"
    data = ark_json.load_path(str(old_manifest))
    data["artifact"] = f"ARK-Core_v{new}_freeze"
    edits[f"artifacts/FREEZE_MANIFEST_v{new}.json"] = json.dumps(data, indent=2) + "\n"
    return edits


def _run_tool(root: Path, *args: str) -> None:
    try:
        proc = subprocess.run(
            [sys.executable, "-I", str(root / "TOOLS" / args[0]), *args[1:]],
            cwd=root, capture_output=True, text=True, timeout=300,
        )
    except subprocess.SubprocessError as exc:  # TimeoutExpired: keep the exit-code contract
        raise BumpError(f"{' '.join(args)} failed: {exc}") from exc
    if proc.returncode != 0:
        raise BumpError(f"{' '.join(args)} failed (exit {proc.returncode}): {proc.stderr.strip() or proc.stdout.strip()}")


def bump(root: Path, new: str) -> List[str]:
    """Perform the bump; returns the written paths. Raises BumpError before writing on any precondition."""
    old = read_version(root)
    if not is_newer(new, old):
        raise BumpError(f"{new} does not have higher precedence than the current VERSION {old}")
    drift = version_drift(root, old)
    if drift:
        raise BumpError("tree is not consistent with VERSION before the bump: " + "; ".join(drift))
    if not re.search(rf"^## \[{re.escape(new)}\]", _text(root, "CHANGELOG.md"), re.M):
        raise BumpError(
            f"CHANGELOG.md has no '## [{new}]' section: write the release notes first "
            "(VERSIONING_POLICY section 3.1: classify the change, name every verdict loosening)"
        )
    for rel in (f"artifacts/FREEZE_MANIFEST_v{new}.json", f"artifacts/RELEASE_BUNDLE_v{new}.sha256"):
        if (root / rel).exists():
            raise BumpError(f"{rel} already exists")

    edits = planned_edits(root, old, new)  # every read and check before the first write
    old_pin = root / "artifacts" / f"RELEASE_BUNDLE_v{old}.sha256"
    # Every path this bump or its two tool processes write or remove, with its bytes
    # before the first write (None = absent), so a later failure can put them back.
    touched = sorted(set(edits) | {f"artifacts/RELEASE_BUNDLE_v{new}.sha256", str(old_pin.relative_to(root))})
    snapshot = {rel: (root / rel).read_bytes() if (root / rel).is_file() else None for rel in touched}
    removed = []
    try:
        for rel, text in edits.items():
            with open(root / rel, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
        _run_tool(root, "freeze_manifest.py", "--regenerate")
        _run_tool(root, "release_bundle.py", "--pin")
        if old_pin.exists():
            old_pin.unlink()
            removed.append(str(old_pin.relative_to(root)))
        _run_tool(root, "freeze_manifest.py")
        after = version_drift(root, new)
        if after:
            raise BumpError("drift after the bump: " + "; ".join(after))
    except BaseException as exc:
        failed = _restore(root, snapshot)
        if failed:
            # The original failure stays the message; the incomplete restore is named
            # in full, never reported as a clean refusal.
            raise BumpError(
                f"{exc!s} -- ROLLBACK INCOMPLETE, check the tree by hand (git status): " + "; ".join(failed)
            ) from exc
        if isinstance(exc, Exception):
            raise BumpError(f"{exc!s} -- every file the bump touched was restored") from exc
        raise  # KeyboardInterrupt/SystemExit: restored, then propagated unchanged
    return sorted(edits) + [f"artifacts/RELEASE_BUNDLE_v{new}.sha256"] + [f"removed {p}" for p in removed]


def _restore(root: Path, snapshot: Dict[str, Optional[bytes]]) -> List[str]:
    """Put every snapshotted path back to its bytes (or absence); returns what could not be.

    Best effort within this process after an ordinary failure or an interrupt: not a
    crash-atomic multi-file transaction (SIGKILL or power loss mid-bump leave a partial
    tree) and no lock against concurrent writers, so run the bump in a clean checkout,
    where ``git status`` shows any leftover and ``git checkout``/``git clean`` undo it.
    Each restore is read back, so a restore that silently did nothing is reported.
    """
    failed: List[str] = []
    for rel, data in snapshot.items():
        path = root / rel
        try:
            if data is None:
                if path.is_file():
                    path.unlink()
                if path.exists():
                    failed.append(f"{rel}: still exists")
            else:
                with open(path, "wb") as fh:
                    fh.write(data)
                if path.read_bytes() != data:
                    failed.append(f"{rel}: bytes differ after restore")
        except OSError as err:
            failed.append(f"{rel}: {err}")
    return failed


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("version", help="the new release version (strict SemVer 2.0.0, no 'v')")
    parser.add_argument("--root", default=str(TOOLS.parent))
    parser.add_argument("--check", action="store_true", help="only report lockstep drift against VERSION")
    args = parser.parse_args(argv)
    root = Path(args.root)
    try:
        if args.check:
            drift = version_drift(root, args.version)
            for line in drift:
                print(line, file=sys.stderr)
            return 1 if drift else 0
        written = bump(root, args.version)
    except (BumpError, OSError, ValueError) as exc:
        print(f"version bump refused: {exc}", file=sys.stderr)
        return 1
    print(f"bumped to {args.version}:")
    for rel in written:
        print("  " + rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
